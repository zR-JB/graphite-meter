// Makes the sign-in and approval pages' assets, which both servers embed from go/internal/auth/assets: the two scripts
// as classic scripts, the stylesheet with the tokens and faces it uses, and the templates with the brand filled in.
// `bun auth/build.ts` writes what changed; with `--check` it fails instead when the committed files differ.
import { readdir } from "node:fs/promises";
import { join } from "node:path";
import { BRAND_LINE, favicon } from "./brand";

const here = import.meta.dir;
const output = join(here, "../../go/internal/auth/assets");
// The only faces the servers serve before sign-in (go/internal/auth/wrap.go, rust/server/src/auth/policy.rs).
const FACES = ["/fonts/ibm-plex-sans-var-latin1.woff2", "/fonts/ibm-plex-mono-600-latin1.woff2"];
const TEMPLATES = ["login.tmpl", "cli.tmpl", "cli-done.tmpl", "continue.tmpl"];
const GENERATED = "Generated by client/auth/build.ts: edit its sources and run it again.";

/** `source`'s module graph as one dependency-free classic script, for a server or the shell to inline and pin. */
async function classicScript(source: string): Promise<string> {
  const entry = join(here, "entry.ts");
  const result = await Bun.build({ entrypoints: [entry], files: { [entry]: source }, format: "iife", minify: true });
  return (await result.outputs[0]!.text()).trim();
}

export const themeScript = () => classicScript(`import { prePaintTheme } from "./theme"; prePaintTheme();`);

type Item = string | { prelude: string; body: Item[] };

/** Statements, declarations and blocks, without comments: as much CSS as tokens.css is written in. */
function parse(css: string): Item[] {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  let at = 0;
  const items = (): Item[] => {
    const list: Item[] = [];
    let start = at;
    for (; at < text.length; at++) {
      const char = text[at];
      if (char === '"' || char === "'") {
        at = text.indexOf(char, at + 1);
        if (at < 0) throw new Error("tokens.css has an unterminated string");
      } else if (char === "{") {
        const prelude = text.slice(start, at).trim();
        at++;
        list.push({ prelude, body: items() });
        start = at + 1;
      } else if (char === ";" || char === "}") {
        const statement = text.slice(start, at).trim();
        if (statement) list.push(statement);
        start = at + 1;
        if (char === "}") return list;
      }
    }
    return list;
  };
  return items();
}

/** auth.css's rules after the `:root` tokens they use, transitively, from tokens.css with each override's media, and
    the faces the pages may load. */
async function stylesheet(): Promise<{ css: string; tokens: Map<string, string> }> {
  const rules = (await Bun.file(join(here, "auth.css")).text()).replace(/\/\*[\s\S]*?\*\//g, "");
  const faces: string[][] = [];
  const roots: { media: string | null; selector: string; declarations: [string, string][] }[] = [];
  const walk = (items: Item[], media: string | null) => {
    for (const item of items) {
      if (typeof item === "string") continue;
      const lines = item.body.filter((line) => typeof line === "string");
      if (item.prelude === "@font-face") {
        if (FACES.some((face) => lines.some((line) => line.includes(`url("${face}")`)))) faces.push(lines);
      } else if (item.prelude.startsWith("@layer")) walk(item.body, media);
      else if (item.prelude.startsWith("@media")) walk(item.body, item.prelude);
      else if (item.prelude.startsWith(":root")) {
        const declarations = lines.map((line): [string, string] => {
          const [name, value] = line.split(/:(.*)/s);
          return [name!.trim(), value!.trim().replace(/\s+/g, " ")];
        });
        roots.push({ media, selector: item.prelude, declarations });
      }
    }
  };
  walk(parse(await Bun.file(join(here, "../src/styles/tokens.css")).text()), null);
  if (faces.length !== FACES.length)
    throw new Error(`tokens.css must declare one face for each of ${FACES.join(", ")}`);

  const declared = Map.groupBy(
    roots.flatMap((rule) => rule.declarations),
    ([name]) => name,
  );
  const local = new Set(Array.from(rules.matchAll(/(--[\w-]+)\s*:/g), (match) => match[1]));
  const used = new Set<string>();
  const use = (text: string) => {
    for (const [, name] of text.matchAll(/var\(\s*(--[\w-]+)/g)) {
      if (used.has(name!) || (!declared.has(name!) && local.has(name!))) continue;
      if (!declared.has(name!)) throw new Error(`auth.css uses ${name}, which src/styles/tokens.css does not declare`);
      used.add(name!);
      for (const [, value] of declared.get(name!)!) use(value);
    }
  };
  use(rules);

  const block = (head: string, lines: string[]) => `${head} {\n${lines.map((line) => `  ${line}`).join("\n")}\n}`;
  const css = [
    `/* ${GENERATED} */`,
    ...faces.map((face) =>
      block(
        "@font-face",
        face.map((line) => `${line.replace(/\s+/g, " ")};`),
      ),
    ),
    ...roots.flatMap(({ media, selector, declarations }) => {
      const kept = declarations.filter(([name]) => !name.startsWith("--") || used.has(name));
      if (!kept.length) return [];
      const rule = block(
        selector,
        kept.map(([name, value]) => `${name}: ${value};`),
      );
      return [media ? block(media, rule.split("\n")) : rule];
    }),
    rules.replace(/\n\s*\n/g, "\n").trim(),
  ];
  const tokens = new Map(roots.filter((rule) => !rule.media).flatMap((rule) => rule.declarations));
  return { css: `${css.join("\n")}\n`, tokens };
}

/** Every file of go/internal/auth/assets by name. */
async function authAssets(): Promise<Record<string, string>> {
  const { css, tokens } = await stylesheet();
  const icon = btoa(favicon(tokens.get("--phase-latency")!, tokens.get("--text")!));
  const assets: Record<string, string> = {
    "auth.css": css,
    "theme.js": `/* ${GENERATED} */\n${await themeScript()}\n`,
    "pending.js": `/* ${GENERATED} */\n${await classicScript(`import { install } from "./pending"; install(window);`)}\n`,
  };
  for (const name of TEMPLATES) {
    const source = await Bun.file(join(here, name)).text();
    for (const marker of ["<!-- icon -->", "<!-- brand -->"])
      if (source.split(marker).length !== 2) throw new Error(`${name} must hold ${marker} once`);
    // The servers strip the banner; nothing may stand before the doctype once they have.
    assets[name] = `<!-- ${GENERATED} -->${source
      .replace("<!-- icon -->", () => `<link rel="icon" href="data:image/svg+xml;base64,${icon}">`)
      .replace("<!-- brand -->", () => BRAND_LINE)}`;
  }
  return assets;
}

if (import.meta.main) {
  const assets = await authAssets();
  const stale: string[] = [];
  for (const name of new Set([...Object.keys(assets), ...(await readdir(output))])) {
    const file = Bun.file(join(output, name));
    const wanted = assets[name];
    // Bytes, not text: a decoder would hide a byte-order mark the servers embed.
    if (wanted === undefined || !(await file.exists()) || !Buffer.from(wanted).equals(await file.bytes()))
      stale.push(name);
  }
  if (process.argv.includes("--check")) {
    if (stale.length) {
      console.error(`go/internal/auth/assets is not what client/auth makes: ${stale.sort().join(", ")}.`);
      console.error("Run `bun run build:auth` in client, and remove any file it does not make.");
      process.exit(1);
    }
  } else for (const name of stale) if (name in assets) await Bun.write(join(output, name), assets[name]!);
}
