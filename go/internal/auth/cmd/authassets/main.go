package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

func main() {
	root := filepath.Join("..", "..", "..", "client", "src", "auth")
	read := func(name string) string {
		value, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			panic(err)
		}
		return string(value)
	}
	source := fmt.Sprintf("// Code generated by go generate; DO NOT EDIT.\n\npackage auth\n\nconst authCSS = %s\nconst loginHTML = %s\nconst cliHTML = %s\nconst cliDoneHTML = %s\nconst continueHTML = %s\n", strconv.Quote(read("auth.css")), strconv.Quote(read("login.tmpl")), strconv.Quote(read("cli.tmpl")), strconv.Quote(read("cli-done.tmpl")), strconv.Quote(read("continue.tmpl")))
	formatted, err := format.Source([]byte(source))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("assets_generated.go", formatted, 0o644); err != nil {
		panic(err)
	}
}
